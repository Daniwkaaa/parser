def targets(scope: str, region: str | None = None) -> list[tuple[str, str]]:
    """Список (місто, область) для пошуку. Для країни міста чергуються між областями, щоб ліміт
    розподілявся рівномірно, а не вичерпувався першою областю."""
    if scope == "oblast":
        if region not in OBLASTS:
            raise ValueError("Оберіть область зі списку")
        return [(c, region) for c in OBLASTS[region]]
    if scope == "country":
        lists = [[(c, r) for c in cities] for r, cities in OBLASTS.items()]
        out: list[tuple[str, str]] = []
        i = 0
        while any(i < len(lst) for lst in lists):
            for lst in lists:
                if i < len(lst):
                    out.append(lst[i])
            i += 1
        return out
    raise ValueError("Невідомий масштаб пошуку")
